async function main() {
  console.log("🇮🇳 Seeding National Hospital & Blood Centre Directory...");

  let updatedCount = 0;
  let createdCount = 0;
  let stockCreatedCount = 0;

  for (const h of NATIONAL_HOSPITALS) {
    // Check if hospital already exists by name
    const existing = await prisma.bloodCenter.findFirst({
      where: { name: h.name },
    });

    let centerId: number;

    if (existing) {
      const updated = await prisma.bloodCenter.update({
        where: { id: existing.id },
        data: {
          city: h.city,
          state: h.state,
          country: h.country,
          address: h.address,
          phone: h.phone,
          facilityType: h.facilityType,
          verificationStatus: h.verificationStatus,
          components: h.components,
          dataSource: h.dataSource,
          popularRank: h.popularRank,
          isMain: h.isMain ?? existing.isMain,
          isActive: true,
          lastStockUpdate: h.stockData ? new Date() : existing.lastStockUpdate,
        },
      });
      centerId = updated.id;
      updatedCount++;
    } else {
      const created = await prisma.bloodCenter.create({
        data: {
          name: h.name,
          type: h.type,
          city: h.city,
          state: h.state,
          country: h.country,
          address: h.address,
          phone: h.phone,
          facilityType: h.facilityType,
          verificationStatus: h.verificationStatus,
          components: h.components,
          dataSource: h.dataSource,
          popularRank: h.popularRank,
          isMain: h.isMain ?? false,
          isActive: true,
          lastStockUpdate: h.stockData ? new Date() : null,
        },
      });
      centerId = created.id;
      createdCount++;
    }

    // Only create or update BloodStock rows if real stockData is provided
    if (h.stockData) {
      for (const [bgStr, units] of Object.entries(h.stockData)) {
        const bloodGroup = bgStr as BloodGroup;
        await prisma.bloodStock.upsert({
          where: {
            centerId_bloodGroup: {
              centerId,
              bloodGroup,
            },
          },
          update: {
            units,
          },
          create: {
            centerId,
            bloodGroup,
            units,
          },
        });
        stockCreatedCount++;
      }
    }
    console.log(`[${NATIONAL_HOSPITALS.indexOf(h) + 1}/${NATIONAL_HOSPITALS.length}] Seeded: ${h.name} (${h.city}, ${h.state})`);
  }

  // Also ensure legacy "Main Blood Bank" is mapped to Gwalior so existing logic works smoothly
  const legacyMain = await prisma.bloodCenter.findFirst({
    where: { isMain: true },
  });
  if (legacyMain) {
    await prisma.bloodCenter.update({
      where: { id: legacyMain.id },
      data: {
        city: "Gwalior",
        state: "Madhya Pradesh",
        country: "India",
        facilityType: "HOSPITAL_WITH_BLOOD_BANK",
        verificationStatus: "VERIFIED",
        popularRank: 1,
      },
    });
  }

  console.log(`\n🎉 Directory Seeding Complete:`);
  console.log(`- Created Centers: ${createdCount}`);
  console.log(`- Updated Centers: ${updatedCount}`);
  console.log(`- Total Records Processed: ${NATIONAL_HOSPITALS.length}`);
  console.log(`- Stock Records Upserted: ${stockCreatedCount}`);
}

main()
  .catch((e) => {
    console.error("Error seeding national directory:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
